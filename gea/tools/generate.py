PG_TYPES = {"string": "text", "boolean": "boolean", "stringArray": "text[]", "dateRange": "date", "dateRangeList": "date"}


def fields_markdown(spec: dict) -> str:
    """The workbook rows next to the database columns that store them: one line per prop."""
    titles = {s["key"]: s["title"] for s in spec["steps"]}

    def stored(form: str, f: dict) -> str:
        table = {"createProject": "Project", "createRun": "Run"}[form]
        kind = PG_TYPES[KINDS[f["type"]]]
        if "table" in f:
            columns = {"ProjectBenefit": "BenefitId", "RunStudyPeriodExclusion": "StartDate`, `EndDate"}[f["table"]]
            return f'`{f["table"]}`.`{columns}` (one row per value)'
        names = f["columns"] if "columns" in f else [f["column"]]
        text = f'`{table}`.' + ", ".join(f"`{name}`" for name in names) + f" {kind}"
        return text + (f' -> `{f["lookup"]}`' if "lookup" in f else "")

    def required(f: dict) -> str:
        if "requiredWhen" in f:
            when = f["requiredWhen"]
            return f'when `{when["prop"]}` is {json.dumps(when["equals"])}'
        return "yes" if f["required"] else "no"

    out = ["# Workbook fields and where they are stored", "",
           f"<!-- {GENERATED} -->", "",
           f"Source: `{spec['source']}` (rows 5 to 40). One line per row of that sheet; Prop, Display name,",
           "Step, Type, Control and Required are the workbook's own columns. Every prop is a column of",
           'gea."Project" or gea."Run", or rows of a child table when it is a list of date ranges or a multiselect',
           "of a lookup. To change a field: edit `poc-data.json`, add an Alembic revision for the column and run",
           "`python gea/tools/generate.py`; `tests/gea/test_migration_sql.py` fails until the three agree.", ""]
    for form, heading in (("createProject", "Create project (`createProject.*`)"), ("createRun", "Create run (`createRun.*`)")):
        out += [f"## {heading}", "",
                "| Prop | Display name | Step | Type | Control | Required | Stored in |",
                "|---|---|---|---|---|---|---|"]
        for f in spec[form]:
            out.append(f'| `{f["prop"]}` | {f["displayName"]} | {titles[f["step"]]} | `{f["type"]}` | {f["control"]} '
                       f'| {required(f)} | {stored(form, f)} |')
        out.append("")
    return "\n".join(out)


# ----------------------------------------------------------------------------- main
def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a generated file is out of date")
    args = parser.parse_args()

    spec = load_spec()
    outputs = {REPO / "gea_api/fields.py": python_fields(spec),
               ROOT / "spec/data-contract.schema.json": json.dumps(contract_schema(spec), indent=2) + "\n",
               ROOT / "spec/fields.md": fields_markdown(spec)}
    base_file = ROOT / "api/openapi.base.yaml"
    if base_file.exists():
        api = openapi(yaml.safe_load(base_file.read_text(encoding="utf-8")), spec)
        outputs[ROOT / "api/openapi.yaml"] = openapi_yaml(api)
        outputs[ROOT / "frontend/src/api/generated.ts"] = typescript(api)
        outputs[ROOT / "frontend/src/api/fields.ts"] = typescript_fields(spec)

    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path.relative_to(REPO))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    if args.check and stale:
        print("Out of date: " + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    print(("Up to date" if not stale else "Wrote " + ", ".join(map(str, stale))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
