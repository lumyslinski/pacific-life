#!/usr/bin/env python3
"""Derive everything that depends on the field list from gea/spec/poc-data.json.

That file is sheet 'POC Data' of the workbook: one entry per prop. The database
columns are written by hand in the Alembic revisions (tests/gea compares them
with the same file); everything else that repeats the field list is generated:

  gea_api/fields.py                        the props, their columns, types, steps and required flags
  spec/data-contract.schema.json           strict JSON Schema of the published contract
  api/openapi.yaml                         api/openapi.base.yaml + the run schemas
  frontend/src/api/generated.ts            TypeScript types of the API (openapi-typescript shape)
  frontend/src/api/fields.ts               the same field list for the Vue client
  spec/fields.md                           the workbook rows next to the columns that store them

Usage:  python gea/tools/generate.py [--check]
Requires PyYAML only.
"""
from __future__ import annotations

import argparse
import copy
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parent
GENERATED = "GENERATED by gea/tools/generate.py - do not edit by hand."
METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"]
# Workbook type (column D of 'POC Data') -> the kind the code works with.
KINDS = {"string": "string", "boolean": "boolean", "array<string>": "stringArray",
         "{start: date, end: date}": "dateRange", "array<{start: date, end: date}>": "dateRangeList"}
CONTROLS = {"text input", "select", "multiselect", "dateRange", "dateRangeList"}


def load_spec() -> dict:
    spec = json.loads((ROOT / "spec/poc-data.json").read_text(encoding="utf-8"))
    steps = [s["key"] for s in spec["steps"]]
    assert steps[0] == "main" and len(set(steps)) == len(steps), "steps: 'main' first, no duplicates"
    for form in ("createProject", "createRun"):
        props = [f["prop"] for f in spec[form]]
        assert len(set(props)) == len(props), f"{form}: duplicate prop"
        for field in spec[form]:
            assert field["type"] in KINDS and field["control"] in CONTROLS and field["step"] in steps, field
            assert sum(key in field for key in ("column", "columns", "table")) == 1, field
            if "requiredWhen" in field:
                assert not field["required"] and field["requiredWhen"]["prop"] in props, field
            if "defaultFrom" in field:
                assert field["defaultFrom"] in props, field
    order = [steps.index(f["step"]) for f in spec["createRun"]]
    assert order == sorted(order), "createRun: props are grouped by step, in step order"
    return spec


def run_config(spec: dict) -> list[dict]:
    """The createRun props after step 'main' (name, treaty): the run configuration."""
    return [f for f in spec["createRun"] if f["step"] != "main"]


def config_steps(spec: dict) -> list[tuple[int, dict, list[dict]]]:
    """(ordinal, step, fields) of the steps Snowflake executes; 'main' is the run identity."""
    return [(i, step, [f for f in spec["createRun"] if f["step"] == step["key"]])
            for i, step in enumerate(spec["steps"]) if step["key"] != "main"]


