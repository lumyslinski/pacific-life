CREATE DATABASE IF NOT EXISTS INSURANCE;
CREATE SCHEMA IF NOT EXISTS INSURANCE.CALC;
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.PARAMETER_BINDINGS (
    MODEL_VERSION VARCHAR, CALCULATION VARCHAR, REGION VARCHAR, PARAMETER VARCHAR,
    FUNCTION_NAME VARCHAR, ARGS_JSON VARCHAR, CONSTANTS_JSON VARCHAR, DEPENDS_JSON VARCHAR,
    PRIMARY KEY (MODEL_VERSION,CALCULATION,REGION,PARAMETER)
);
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.MODEL_OBJECTIVES (
    MODEL_VERSION VARCHAR PRIMARY KEY, FUNCTION_NAME VARCHAR
);
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.CALCULATION_RUNS (
    RUN_ID VARCHAR PRIMARY KEY, REQUEST_JSON VARCHAR, MODEL_SNAPSHOT_JSON VARCHAR,
    RESULT_JSON VARCHAR
);
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.CALCULATION_AUDIT (
    RUN_ID VARCHAR, POLICY_ID VARCHAR, ITERATION INTEGER, SNAPSHOT_JSON VARCHAR,
    PRIMARY KEY (RUN_ID,POLICY_ID,ITERATION)
);
