CREATE SCHEMA IF NOT EXISTS INSURANCE.RELEASES;
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.FUNCTION_DRAFTS (
    FUNCTION_ID VARCHAR PRIMARY KEY, REVISION INTEGER, DOCUMENT_JSON VARCHAR
);
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.FUNCTION_RELEASES (
    FUNCTION_ID VARCHAR, REVISION INTEGER, FUNCTION_NAME VARCHAR, DOCUMENT_JSON VARCHAR,
    PRIMARY KEY (FUNCTION_ID,REVISION)
);
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.CONFIG_REVISIONS (
    CONFIG_ID VARCHAR, REVISION INTEGER, DOCUMENT_JSON VARCHAR, PRIMARY KEY (CONFIG_ID,REVISION)
);
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.CORE_MODELS (
    MODEL_ID VARCHAR PRIMARY KEY, DOCUMENT_JSON VARCHAR
);
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.VARIATIONS (
    MODEL_ID VARCHAR PRIMARY KEY, REVISION INTEGER, DOCUMENT_JSON VARCHAR
);
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.VARIATION_REVISIONS (
    MODEL_ID VARCHAR, REVISION INTEGER, DOCUMENT_JSON VARCHAR, PRIMARY KEY (MODEL_ID,REVISION)
);
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.AUDIT_EVENTS (
    EVENT_ID VARCHAR PRIMARY KEY, AGGREGATE_ID VARCHAR, REVISION INTEGER, DOCUMENT_JSON VARCHAR
);
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.AUDIT_OUTBOX (
    EVENT_ID VARCHAR PRIMARY KEY, DELIVERED BOOLEAN DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS INSURANCE.CALC.COMMAND_RESULTS (
    REQUEST_ID VARCHAR PRIMARY KEY, REQUEST_HASH VARCHAR, DOCUMENT_JSON VARCHAR
);
