CREATE OR REPLACE FUNCTION INSURANCE.CALC.CORE_LIMIT_AMOUNT_V1(
    amount NUMBER(18,2), cap NUMBER(18,2)
) RETURNS NUMBER(18,2) LANGUAGE SQL
AS $$ LEAST(amount, cap) $$;

CREATE OR REPLACE FUNCTION INSURANCE.CALC.CORE_LIMIT_RELATIVE_V1(
    amount NUMBER(18,2), reference_amount NUMBER(18,2), ratio NUMBER(18,8)
) RETURNS NUMBER(18,2) LANGUAGE SQL
AS $$ LEAST(amount, ROUND(reference_amount * ratio, 2)) $$;

CREATE OR REPLACE FUNCTION INSURANCE.CALC.REGIONAL_CAP_V1(
    amount NUMBER(18,2), cap NUMBER(18,2)
) RETURNS NUMBER(18,2) LANGUAGE SQL
AS $$ LEAST(amount, cap) $$;

CREATE OR REPLACE FUNCTION INSURANCE.CALC.CORE_IDENTITY_V1(
    amount NUMBER(18,2)
) RETURNS NUMBER(18,2) LANGUAGE SQL
AS $$ amount $$;

CREATE OR REPLACE FUNCTION INSURANCE.CALC.OBJECTIVE_RELATIVE_CHANGE_V1(
    baseline NUMBER(18,2), calculated NUMBER(18,2)
) RETURNS NUMBER(18,8) LANGUAGE SQL
AS $$ IFF(baseline = 0, 0, POWER((calculated - baseline) / NULLIF(baseline, 0), 2)) $$;
